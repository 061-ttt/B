// 画面を一巡してスクリーンショットを撮る（目視確認用）
import { chromium } from '@playwright/test';
const SP = process.argv[2] ?? '.';
const BASE = process.env.BASE ?? 'http://127.0.0.1:8787';
const b = await chromium.launch({ executablePath: process.env.PW_CHROME_PATH, args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const p = await (await b.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true })).newPage();
await p.goto(BASE);
await p.waitForFunction(() => !document.getElementById('skeleton'), null, { timeout: 40000 });
const add = async (fish, place, method) => {
  await p.getByTestId('fab').click();
  await p.getByTestId('fish-input').fill(fish);
  await p.locator('[aria-label="魚の候補"] button').first().click();
  await p.getByTestId('place-input').fill(place);
  await p.locator('[aria-label="産地の候補"] button').first().click();
  if (method) await p.getByTestId('add-sheet').getByRole('button', { name: method, exact: true }).click();
  await p.getByTestId('submit').click();
  await p.waitForTimeout(700);
};
await p.waitForTimeout(3000);
await p.getByTestId('fab').click();
await p.getByTestId('tag-input').fill('ノルウェー産 塩さば');
await p.getByTestId('parse').click();
await p.waitForTimeout(600);
await p.screenshot({ path: `${SP}/t1-add.png` });
await p.keyboard.press('Escape');
await p.waitForTimeout(400);
for (const [f, pl, m] of [['さけ', '北海道', '天然'], ['さけ', '北海道'], ['さんま', '根室'], ['ほたて', '青森'], ['さば', '銚子'], ['かき', '広島', '養殖'], ['のり', '佐賀', '養殖'], ['ぶり', '鹿児島', '養殖'], ['かつお', '焼津'], ['あじ', '長崎'], ['たら', '北海道']]) await add(f, pl, m);
await p.getByTestId('view-japan').click();
await p.waitForTimeout(3000);
await p.screenshot({ path: `${SP}/t2-japan.png` });
for (const [f, pl, m] of [['さけ', 'チリ', '養殖'], ['さけ', 'ノルウェー', '養殖'], ['えび', 'ベトナム', '養殖'], ['えび', 'インド', '養殖'], ['たこ', 'モロッコ'], ['まぐろ', '台湾'], ['さば', 'ノルウェー']]) await add(f, pl, m);
await p.getByTestId('view-world').click();
await p.waitForTimeout(3500);
await p.screenshot({ path: `${SP}/t3-world.png` });
await p.locator('[data-tab=zukan]').click();
await p.locator('[data-fish=salmon] .acc-head').click();
await p.waitForTimeout(700);
await p.screenshot({ path: `${SP}/t4-zukan.png` });
await p.locator('[data-tab=sheet]').click();
await p.getByTestId('pick-facts').click();
await p.getByTestId('seeds').click();
await p.waitForTimeout(700);
await p.screenshot({ path: `${SP}/t5-sheet.png` });
await p.locator('[data-tab=map]').click();
await p.getByTestId('legend-btn').click();
await p.waitForTimeout(700);
await p.screenshot({ path: `${SP}/t6-legend.png` });
await b.close();
